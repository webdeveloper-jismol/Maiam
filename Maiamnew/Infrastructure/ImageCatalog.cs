namespace Maiamnew.Infrastructure
{
    /// <summary>
    /// One optimised image. All renditions share the same aspect ratio and live at
    /// /assets/images/{Key}-{width}.webp.
    /// </summary>
    public sealed record ImageAsset(string Key, int Width, int Height, string Alt, IReadOnlyList<int> Widths)
    {
        public string Url(int width) => $"/assets/images/{Key}-{width}.webp";

        public string LargestUrl => Url(Widths[^1]);

        /// <summary>Middle rendition, used as the plain src fallback.</summary>
        public string DefaultUrl => Url(Widths[Widths.Count / 2]);

        public string SrcSet => string.Join(", ", Widths.Select(w => $"{Url(w)} {w}w"));

        public bool IsPortrait => Height > Width;
    }

    /// <summary>
    /// Registry of the optimised MAIAM images. Entries are generated by the image
    /// pipeline into ImageCatalog.Generated.cs.
    /// </summary>
    public static partial class ImageCatalog
    {
        private static readonly Dictionary<string, ImageAsset> Items = new(StringComparer.OrdinalIgnoreCase);

        static ImageCatalog() => Register();

        static partial void Register();

        private static void Add(string key, int width, int height, string alt, params int[] widths) =>
            Items[key] = new ImageAsset(key, width, height, alt, widths);

        public static ImageAsset Get(string key) =>
            Items.TryGetValue(key, out var asset)
                ? asset
                : throw new KeyNotFoundException($"Image '{key}' is not registered in the image catalog.");

        public static IEnumerable<ImageAsset> All => Items.Values;
    }
}
